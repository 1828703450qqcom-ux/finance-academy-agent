# ==================== 提示词组合工具 ====================

def build_topic_scout_prompt(research_question: str, context: str = "") -> str:
    """构建选题探索的用户消息"""
    msg = f"研究问题/想法：{research_question}"
    if context:
        msg += f"\n\n补充背景：{context}"
    msg += "\n\n请帮我：1) 评估这个选题的可行性；2) 给出3个具体的论文选题建议；3) 推荐合适的研究方法。"
    return msg


def build_design_doctor_prompt(
    research_question: str,
    data_type: str = "panel",
    dependent_var: str = "",
    independent_vars: str = "",
    context: str = "",
) -> str:
    """构建方法对比的用户消息"""
    msg = f"研究问题：{research_question}\n数据类型：{data_type}"
    if dependent_var:
        msg += f"\n被解释变量：{dependent_var}"
    if independent_vars:
        msg += f"\n解释变量：{independent_vars}"
    if context:
        msg += f"\n补充信息：{context}"
    msg += "\n\n请帮我：1) 比较适合这个研究问题的因果识别策略；2) 推荐最佳方法并说明理由；3) 给出回归方程和检验清单。"
    return msg


def build_paper_draft_prompt(
    section: str,
    research_info: str,
    findings: str = "",
    contributions: str = "",
) -> str:
    """构建论文写作的用户消息"""
    msg = f"论文部分：{section}\n研究信息：{research_info}"
    if findings:
        msg += f"\n主要发现：{findings}"
    if contributions:
        msg += f"\n创新贡献：{contributions}"
    msg += f"\n\n请帮我撰写{section}部分的草稿，要求符合学术论文规范。"
    return msg


def build_review_prompt(paper_text: str, focus: str = "") -> str:
    """构建审稿模拟的用户消息"""
    msg = f"论文内容：\n{paper_text}"
    if focus:
        msg += f"\n\n重点关注：{focus}"
    msg += "\n\n请按照 Reviewer → Critic → Defender → Fixer 四阶段流程进行审稿模拟。"
    return msg
