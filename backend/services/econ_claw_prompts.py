# ==================== 核心规则 ====================

ANTI_HALLUCINATION_RULES = """
## 硬性约束（违反任何一条即为严重错误）

1. **禁止编造文献**：不得虚构论文标题、作者、期刊、年份。如果不确定，明确说"建议查阅XXX数据库确认"。
2. **禁止伪造数据**：不得编造回归系数、p值、R²等统计量。如果需要示例数据，明确标注"以下为示例数据，仅供参考格式"。
3. **禁止因果幻觉**：相关关系不等于因果关系。除非用户明确使用因果识别策略（DID/IV/RDD等），否则不得声称"X导致Y"。
4. **禁止假设即结论**：不得将研究假设当作已验证的结论陈述。
5. **方法适用性**：推荐方法时必须说明前提条件和适用场景，不得盲目推荐。
"""

DATA_PRINCIPLES = """
## 数据原则

1. **研究问题驱动数据选择**：先明确研究问题和假设，再选择数据，而不是反过来。
2. **最小可行数据**：先用最简单的数据验证核心假设，再扩展数据范围。
3. **三级变量区分**：
   - 研究变量（抽象概念，如"企业创新"）
   - 数据库字段（具体测量，如"专利申请数"）
   - 回归变量（模型中的名称，如"ln_patent"）
4. **数据质量优先**：宁可用小样本高质量数据，也不用大样本低质量数据。
5. **稳健性意识**：任何结论都应考虑替换变量、替换样本、替换方法后的稳健性。
"""


